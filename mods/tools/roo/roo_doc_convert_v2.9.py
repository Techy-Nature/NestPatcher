#!/usr/bin/env python3
"""Turn William's "(16.1) TiTS - Roo, Crew Member Expansion" Google Doc (exported as Markdown)
into the text table used by TN_RooCrew_v2.9.js.

Usage: python3 roo_doc_convert_v2.9.py <docB.md> <out.js>

Each kept line becomes [docLine, kind, text]:
  kind 0 = prose paragraph (quotes turned into <i>“...”</i>, apostrophes curled, markdown escapes removed)
  kind 1 = a "// note" line (the text is dropped; the mod's COND table decides what each one means)
The doc's own {key: a / b} markup and [pc.x] / [roo.x] tags are kept and resolved in the game.
"""
import json, re, sys

START = 341  # "F27 \\BACK OFFICE"; everything above is the table of contents and the summary


def unesc(s):
    return re.sub(r'\\([\\`*_{}\[\]()#+\-.!<>|~"\'=&])', r'\1', s)


def quotes(s):
    out, n = '', 0
    for c in s:
        if c == '"':
            n += 1
            out += '<i>“' if n % 2 else '”</i>'
        else:
            out += c
    if n % 2:
        out += '</i>'
    return out


def apos(s):
    out, depth = '', 0
    for c in s:
        if c in '[<':
            depth += 1
        elif c in ']>':
            depth = max(0, depth - 1)
        out += '’' if (c == "'" and depth == 0) else c
    return out


def classify(raw):
    s = unesc(raw.rstrip('\n')).replace(' ', ' ').strip()
    if not s:
        return None, None
    t = re.sub(r'^[-*]\s+', '', s).strip()
    t2 = t.replace('*', '').strip()
    if s.startswith('#'):
        return 'h', s
    if t.startswith('#'):
        return ('c', t2) if '//' in t else ('h', t)
    if t2.startswith('//') or (t2.startswith('\\\\') and 'TBW' in t2[:8]):
        return 'c', t2
    if re.fullmatch(r'(\s*\[[^\]]+\]\s*)+(\s*\\\\.*|\s*//.*)?', t2):
        return 'b', t2
    return 'p', t


def clean(s):
    s = s.replace('**', '').replace(' // ', ' / ')
    s = apos(quotes(s.rstrip()))
    return s.replace('<i></i>', '')


def main(src, dst):
    rows = []
    for n, raw in enumerate(open(src, encoding='utf-8'), 1):
        if n < START:
            continue
        k, s = classify(raw)
        if k == 'p':
            rows.append([n, 0, clean(s)])
        elif k == 'c':
            rows.append([n, 1, ''])
    js = ('/* Generated by mods/tools/roo/roo_doc_convert_v2.9.py from William\'s Roo crew doc. Do not hand-edit. */\n'
          'var DOC = ' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n')
    open(dst, 'w', encoding='utf-8').write(js)
    print(len(rows), 'rows,', len(js), 'bytes')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
